# Database
# https://docs.djangoproject.com/en/6.1/ref/settings/#databases

def _db():
    """SQLite por defecto (desarrollo). En producción: DATABASE_URL=postgres://usuario:clave@host:5432/base"""
    url = os.environ.get('DATABASE_URL', '')
    if url.startswith(('postgres://', 'postgresql://')):
        from urllib.parse import urlparse
        u = urlparse(url)
        return {'ENGINE': 'django.db.backends.postgresql', 'NAME': u.path.lstrip('/'), 'USER': u.username or '',
                'PASSWORD': u.password or '', 'HOST': u.hostname or '', 'PORT': u.port or '', 'CONN_MAX_AGE': 60,
                'CONN_HEALTH_CHECKS': True}
    if url.startswith('sqlite:///'):  # otra base SQLite (p. ej. una copia para probar sin tocar la de trabajo)
        return {'ENGINE': 'django.db.backends.sqlite3', 'NAME': url[len('sqlite://'):]}
    return {'ENGINE': 'django.db.backends.sqlite3', 'NAME': BASE_DIR / 'db.sqlite3'}


DATABASES = {'default': _db()}


